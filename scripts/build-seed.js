function slug(name) {
  return name.toLowerCase().replace(/[^a-zа-яё0-9]+/gi, '-').replace(/^-|-$/g, '');
}

/** Синтезированная помесячная история за 24 месяца: previous -> current, со сглаженным шумом. */
function buildHistory(id, from, to, clubName) {
  const rand = rng(id);
  const points = 24;
  const out = [];
  for (let i = 0; i < points; i++) {
    const t = i / (points - 1);
    // Плавная S-кривая между стартом и финишем + небольшой шум.
    const ease = t * t * (3 - 2 * t);
    const base = from + (to - from) * ease;
    const noise = (rand() - 0.5) * (Math.max(from, to) * 0.05) * (i === points - 1 ? 0 : 1);
    const value = Math.max(0.5, Math.round((base + noise) * 20) / 20);
    const d = new Date(Date.UTC(2024, 8 + i, 1));
    out.push({
      date: d.toISOString().slice(0, 10),
      value: Math.round(value * 1_000_000),
      clubName,
    });
  }
  out[out.length - 1].date = SNAPSHOT;
  out[out.length - 1].value = Math.round(to * 1_000_000);
  return out;
}

